                if not q:
                    continue
                trigger = float(item.get("trigger", 0) or 0)
                ltp = q["ltp"]
                gap = ((trigger / ltp) - 1) * 100 if ltp else None
                near.append({"SYMBOL": symbol, "LTP": ltp, "TRIGGER": trigger,
                             "TO TRIGGER %": gap, "SCORE": item.get("static_score"),
                             "DAY %": q.get("change_pct")})
