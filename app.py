def db():
    con = sqlite3.connect(DB_PATH, check_same_thread=False)
    con.row_factory = sqlite3.Row
    return con


def init_db():
    with db() as con:
        con.execute("""CREATE TABLE IF NOT EXISTS settings (
            id INTEGER PRIMARY KEY CHECK(id=1), capital REAL NOT NULL, allocation REAL NOT NULL
        )""")
        con.execute("""INSERT OR IGNORE INTO settings(id,capital,allocation) VALUES(1,1000000,50000)""")
        con.execute("""CREATE TABLE IF NOT EXISTS trades (
            id INTEGER PRIMARY KEY AUTOINCREMENT, symbol TEXT NOT NULL, opened_at TEXT NOT NULL,
            entry REAL NOT NULL, qty INTEGER NOT NULL, remaining_qty INTEGER NOT NULL,
            invested REAL NOT NULL, initial_sl REAL NOT NULL, active_sl REAL NOT NULL,
            t1 REAL NOT NULL, t2 REAL NOT NULL, t3 REAL NOT NULL, t4 REAL NOT NULL,
            t1_done INTEGER DEFAULT 0, t2_done INTEGER DEFAULT 0, t3_done INTEGER DEFAULT 0,
            trailing INTEGER DEFAULT 0, last_price REAL, status TEXT DEFAULT 'OPEN',
            realised_pnl REAL DEFAULT 0, setup_month TEXT, trigger_price REAL,
            monthly_sma20 REAL, monthly_sma10 REAL
        )""")
        con.execute("""CREATE TABLE IF NOT EXISTS events (
            id INTEGER PRIMARY KEY AUTOINCREMENT, trade_id INTEGER NOT NULL,
            event_time TEXT NOT NULL, event TEXT NOT NULL, qty INTEGER DEFAULT 0,
            price REAL DEFAULT 0, pnl REAL DEFAULT 0
        )""")
        # Safe schema migration for databases created by earlier app versions.
        trade_columns = {row[1] for row in con.execute("PRAGMA table_info(trades)").fetchall()}
        if "t4_done" not in trade_columns:
            con.execute("ALTER TABLE trades ADD COLUMN t4_done INTEGER DEFAULT 0")


def get_settings():
    with db() as con:
        row = con.execute("SELECT capital, allocation FROM settings WHERE id=1").fetchone()
        return float(row["capital"]), float(row["allocation"])


def save_settings(capital, allocation):
    with db() as con:
        con.execute("UPDATE settings SET capital=?, allocation=? WHERE id=1", (capital, allocation))


def load_trades(status=None):
    with db() as con:
        if status:
            rows = con.execute("SELECT * FROM trades WHERE status=? ORDER BY id DESC", (status,)).fetchall()
        else:
            rows = con.execute("SELECT * FROM trades ORDER BY id DESC").fetchall()
        return [dict(r) for r in rows]


def get_watchlist():
    if not WATCH_FILE.exists():
        return []
    try:
        data = json.loads(WATCH_FILE.read_text(encoding="utf-8"))
        return data.get("items", [])
    except Exception:
        return []


def market_snapshot(symbol, include_monthly=True):
    ticker = symbol if symbol.endswith(".NS") else symbol + ".NS"
    price, source = None, "Unavailable"
    try:
        intraday = yf.download(ticker, period="1d", interval="1m", progress=False, auto_adjust=False, threads=False)
        if intraday is not None and not intraday.empty:
            close = intraday["Close"]
            if isinstance(close, pd.DataFrame):
                close = close.iloc[:, 0]
            close = close.dropna()
            if not close.empty:
                price, source = float(close.iloc[-1]), "1-minute Yahoo Finance"
    except Exception:
        pass
    if price is None:
        try:
            daily = yf.download(ticker, period="5d", interval="1d", progress=False, auto_adjust=False, threads=False)
            if daily is not None and not daily.empty:
                close = daily["Close"]
                if isinstance(close, pd.DataFrame):
                    close = close.iloc[:, 0]
                close = close.dropna()
                if not close.empty:
                    price, source = float(close.iloc[-1]), "Daily close fallback (not live)"
        except Exception:
            pass

    sma20 = sma10 = None
    if include_monthly:
      try:
        monthly = yf.download(ticker, period="5y", interval="1mo", progress=False, auto_adjust=False, threads=False)
        if monthly is not None and not monthly.empty:
            close = monthly["Close"]
            if isinstance(close, pd.DataFrame):
                close = close.iloc[:, 0]
            close = close.dropna()
            # Exclude the developing month; SMA values must not repaint intramonth.
            if len(close) > 1:
                last_month = pd.Timestamp(close.index[-1]).to_period("M")
                current_month = pd.Timestamp.now(tz=IST).tz_localize(None).to_period("M")
                completed = close.iloc[:-1] if last_month == current_month else close
                if len(completed) >= 20:
                    sma20 = float(completed.rolling(20).mean().iloc[-1])
                if len(completed) >= 10:
                    sma10 = float(completed.rolling(10).mean().iloc[-1])
      except Exception:
        pass
    return price, source, sma20, sma10


@st.cache_data(ttl=45, show_spinner=False)
def get_live_quotes(symbols):
    """Batch-fetch 1-minute LTP and session stats for the whole desk."""
    symbols = sorted({str(s).replace(".NS", "") for s in symbols if s})
    if not symbols:
        return {}
    tickers = [s + ".NS" for s in symbols]
    try:
        raw = yf.download(
            tickers, period="5d", interval="1m", group_by="ticker",
            auto_adjust=False, prepost=False, threads=True, progress=False,
        )
    except Exception:
        return {}

    quotes = {}
    today = pd.Timestamp.now(tz=IST).date()
    for symbol, ticker in zip(symbols, tickers):
        try:
            if isinstance(raw.columns, pd.MultiIndex):
                if ticker in raw.columns.get_level_values(0):
                    frame = raw[ticker].copy()
                elif ticker in raw.columns.get_level_values(1):
                    frame = raw.xs(ticker, axis=1, level=1).copy()
                else:
                    continue
            else:
                if len(symbols) != 1:
                    continue
                frame = raw.copy()
            frame = frame.dropna(subset=["Close"])
            if frame.empty:
                continue
            idx = frame.index
            if idx.tz is None:
                idx = idx.tz_localize("UTC").tz_convert(IST)
            else:
                idx = idx.tz_convert(IST)
            frame.index = idx
            current = frame[frame.index.date == today]
            if current.empty:
                current = frame
            ltp = float(current["Close"].dropna().iloc[-1])
            previous_days = frame[frame.index.date < today]
            previous_close = float(previous_days["Close"].dropna().iloc[-1]) if not previous_days.empty else None
            day_high = float(current["High"].max()) if "High" in current else ltp
            day_low = float(current["Low"].min()) if "Low" in current else ltp
            volume = int(current["Volume"].fillna(0).sum()) if "Volume" in current else 0
            change = ((ltp / previous_close) - 1) * 100 if previous_close else None
            quotes[symbol] = {
                "ltp": ltp, "previous_close": previous_close, "change_pct": change,
                "day_high": day_high, "day_low": day_low, "volume": volume,
                "time": frame.index[-1].strftime("%H:%M:%S"),
                "source": "Yahoo Finance · 1m",
            }
        except Exception:
            continue
    return quotes


@st.cache_data(ttl=90, show_spinner=False)
def get_chart_history(symbol, period, interval):
    """Fetch OHLCV history for the chart workspace."""
    ticker = symbol if symbol.endswith(".NS") else symbol + ".NS"
    try:
        frame = yf.download(
            ticker, period=period, interval=interval, auto_adjust=False,
            prepost=False, progress=False, threads=False,
        )
        if frame is None or frame.empty:
            return pd.DataFrame()
        if isinstance(frame.columns, pd.MultiIndex):
            # yfinance may return a one-ticker MultiIndex depending on its version.
            frame.columns = frame.columns.get_level_values(0)
        frame = frame.rename(columns={str(c).title(): str(c).title() for c in frame.columns})
        needed = ["Open", "High", "Low", "Close"]
        if not all(c in frame.columns for c in needed):
            return pd.DataFrame()
        keep = needed + (["Volume"] if "Volume" in frame.columns else [])
        frame = frame[keep].dropna(subset=["Open", "High", "Low", "Close"]).copy()
        frame.index = pd.to_datetime(frame.index)
        if frame.index.tz is not None:
            frame.index = frame.index.tz_convert(IST).tz_localize(None)
        return frame
    except Exception:
        return pd.DataFrame()


def build_price_chart(frame, symbol, levels, interval_label):
    """Build a terminal-style candlestick + volume chart with strategy levels."""
    rows = 2 if "Volume" in frame.columns else 1
    heights = [0.76, 0.24] if rows == 2 else [1.0]
    fig = make_subplots(
        rows=rows, cols=1, shared_xaxes=True, vertical_spacing=0.035,
        row_heights=heights,
    )
    fig.add_trace(go.Candlestick(
        x=frame.index, open=frame["Open"], high=frame["High"],
        low=frame["Low"], close=frame["Close"], name=symbol,
        increasing_line_color="#00e5a8", decreasing_line_color="#ff5577",
        increasing_fillcolor="#00b889", decreasing_fillcolor="#d94365",
    ), row=1, col=1)
    if rows == 2:
        volume_colors = [
            "rgba(0,229,168,.48)" if c >= o else "rgba(255,85,119,.48)"
            for o, c in zip(frame["Open"], frame["Close"])
        ]
        fig.add_trace(go.Bar(
            x=frame.index, y=frame["Volume"], name="Volume",
            marker_color=volume_colors, hovertemplate="Volume: %{y:,.0f}<extra></extra>",
        ), row=2, col=1)

    palette = {
        "LTP": "#f5f7ff", "TRIGGER": "#00f5d4", "ENTRY": "#39a0ff",
        "INITIAL SL": "#ff5577", "ACTIVE SL": "#ff9f43",
        "T1": "#b7f34a", "T2": "#c4a7ff", "T3": "#f5c451",
        "T4": "#ff80bf", "MONTHLY SMA20": "#7aa2ff",
        "MONTHLY SMA10": "#a78bfa", "ATH LEVEL": "#8ca4b8",
    }
    for label, value in levels.items():
        if value is None:
            continue
        try:
            value = float(value)
            if not math.isfinite(value) or value <= 0:
                continue
        except (TypeError, ValueError):
            continue
        color = palette.get(label, "#8ca4b8")
        dash = "solid" if label in ("LTP", "ACTIVE SL") else "dot" if "SMA" in label else "dash"
        fig.add_hline(
            y=value, line_color=color, line_width=1.25, line_dash=dash,
            annotation_text=f"{label}  ₹{value:,.2f}",
            annotation_position="right", annotation_font_color=color,
            annotation_font_size=10, row=1, col=1,
        )

    fig.update_layout(
        template="plotly_dark", height=660 if rows == 2 else 540,
        paper_bgcolor="rgba(5,10,18,0)", plot_bgcolor="rgba(7,14,24,.92)",
        margin=dict(l=12, r=115, t=38, b=12),
        title=dict(text=f"{symbol}  //  {interval_label} PRICE MATRIX", x=0.015,
                   font=dict(family="Orbitron, monospace", size=14, color="#dffaff")),
        font=dict(family="IBM Plex Mono, monospace", color="#9db3c5", size=10),
        xaxis_rangeslider_visible=False, hovermode="x unified",
        legend=dict(orientation="h", y=1.02, x=0.01),
        showlegend=False,
    )
    fig.update_xaxes(
        showgrid=True, gridcolor="rgba(67,103,128,.16)",
        zeroline=False, showspikes=True, spikemode="across",
        spikesnap="cursor", spikethickness=1, spikecolor="#00f5d4",
    )
    fig.update_yaxes(showgrid=True, gridcolor="rgba(67,103,128,.16)", zeroline=False, side="right", row=1, col=1)
    if rows == 2:
        fig.update_yaxes(showgrid=False, row=2, col=1, side="right")
    return fig


def event(con, trade_id, name, qty, price, pnl):
    con.execute(
        "INSERT INTO events(trade_id,event_time,event,qty,price,pnl) VALUES(?,?,?,?,?,?)",
        (trade_id, datetime.now().astimezone().isoformat(timespec="seconds"), name, qty, price, pnl),
    )


def update_trade(trade, price, sma10):
    """Apply target milestones to available quantity; conservative if a refresh skips levels."""
    with db() as con:
        row = con.execute("SELECT * FROM trades WHERE id=?", (trade["id"],)).fetchone()
        if row is None or row["status"] != "OPEN":
            return
        t = dict(row)
        qty = int(t["remaining_qty"])
        realised = float(t["realised_pnl"])
        active_sl = float(t["active_sl"])
        updates = {}

        if price <= active_sl:
            pnl = (price - t["entry"]) * qty
            realised += pnl
            event(con, t["id"], "STOP LOSS / TRAILING EXIT", qty, price, pnl)
            con.execute("UPDATE trades SET remaining_qty=0, realised_pnl=?, last_price=?, status='CLOSED' WHERE id=?",
                        (realised, price, t["id"]))
            return

        if not t["t1_done"] and price >= t["t1"]:
            sell = min(qty, max(1, math.floor(t["qty"] * 0.50)))
            pnl = (t["t1"] - t["entry"]) * sell
            qty -= sell
            realised += pnl
            event(con, t["id"], "T1 +25%: book 50% of initial quantity", sell, t["t1"], pnl)
            updates["t1_done"] = 1

        if not t["t2_done"] and price >= t["t2"]:
            active_sl = max(active_sl, float(t["entry"]))
            event(con, t["id"], "T2 +40%: stop moved to cost", 0, t["entry"], 0)
            updates["t2_done"] = 1

        if not t["t3_done"] and price >= t["t3"] and qty > 0:
            sell = min(qty, max(1, math.floor(qty * 0.50)))
            pnl = (t["t3"] - t["entry"]) * sell
            qty -= sell
            realised += pnl
            event(con, t["id"], "T3 +50%: book 50% of available quantity", sell, t["t3"], pnl)
            updates["t3_done"] = 1

        trailing = int(t["trailing"])
        if price >= t["t4"] and not t.get("t4_done", 0):
            trailing = 1
            updates["t4_done"] = 1
            event(con, t["id"], "T4 +100%: monthly SMA10 trailing activated", 0, t["t4"], 0)
        if trailing and sma10 is not None and sma10 > active_sl:
            active_sl = float(sma10)
            event(con, t["id"], "Monthly SMA10 trailing stop updated", 0, active_sl, 0)

        status = "CLOSED" if qty <= 0 else "OPEN"
        con.execute("""UPDATE trades SET remaining_qty=?, realised_pnl=?, active_sl=?,
            t1_done=?, t2_done=?, t3_done=?, t4_done=?, trailing=?, last_price=?, status=? WHERE id=?""",
            (qty, realised, active_sl, updates.get("t1_done", t["t1_done"]),
             updates.get("t2_done", t["t2_done"]), updates.get("t3_done", t["t3_done"]),
             updates.get("t4_done", t.get("t4_done", 0)), trailing, price, status, t["id"]))
        if status == "CLOSED":
            event(con, t["id"], "POSITION FULLY BOOKED", 0, price, 0)


def open_trade(item, price, allocation, sma20, sma10):
    symbol = item["symbol"]
    qty = math.floor(allocation / price)
    if qty < 1:
        return False, "Price is higher than the per-trade allocation; quantity would be zero."
    if sma20 is None:
        return False, "Monthly SMA20 unavailable; cannot calculate the specified initial stop."
    initial_sl = max(price * 0.75, sma20)
    if initial_sl >= price:
        return False, "Monthly SMA20 is at/above entry; setup skipped because it gives no valid risk stop."
    with db() as con:
        exists = con.execute("SELECT id FROM trades WHERE symbol=? AND status='OPEN'", (symbol,)).fetchone()
        if exists:
            return False, "Already have an open paper position in this stock."
        # Do not re-enter the same symbol after it has already been paper-traded.
        prior = con.execute("SELECT id FROM trades WHERE symbol=?", (symbol,)).fetchone()
        if prior:
            return False, "This symbol has already been traded in this paper portfolio."
        invested = qty * price
        cur = con.execute("""INSERT INTO trades(symbol,opened_at,entry,qty,remaining_qty,invested,
            initial_sl,active_sl,t1,t2,t3,t4,last_price,setup_month,trigger_price,monthly_sma20,monthly_sma10)
            VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
            (symbol, datetime.now().astimezone().isoformat(timespec="seconds"), price, qty, qty,
             invested, initial_sl, initial_sl, price*1.25, price*1.40, price*1.50, price*2.0,
             price, item.get("setup_month"), float(item.get("trigger", 0)), sma20, sma10))
        event(con, cur.lastrowid, "PAPER ENTRY", qty, price, 0)
    return True, f"Paper entry: {qty} shares of {symbol} at ₹{price:,.2f}."


def portfolio_metrics(capital, trades):
    open_trades = [t for t in trades if t["status"] == "OPEN"]
    closed_trades = [t for t in trades if t["status"] == "CLOSED"]
    invested = sum(t["entry"] * t["remaining_qty"] for t in open_trades)
    realised = sum(t["realised_pnl"] for t in trades)
    unrealised = sum(((t["last_price"] or t["entry"]) - t["entry"]) * t["remaining_qty"] for t in open_trades)
    cash = capital - invested + realised
    equity = cash + invested + unrealised
    return open_trades, closed_trades, cash, equity, realised, unrealised


